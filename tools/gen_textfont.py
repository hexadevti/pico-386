# gen_textfont.py -- builds pico386/src/pc/pc_textfont.h, the hand-drawn text fonts for 80x25.
#
# 80 columns get 4 pixels each on the 320x320 panel. Shrinking the VGA's 8x16 font to that size
# blurs it, so the glyphs that matter are drawn here for the cell, 3 pixels wide plus a gap column,
# in two heights (Settings > Font size):
#   4x12: capitals on rows 2-9, x-height rows 4-9, descenders rows 10-11 (25 rows fill 300 lines)
#   4x8:  capitals on rows 1-6, x-height rows 3-6, descender row 7      (25 rows fill 200 lines)
# Box drawing and blocks are generated so that they join across cells.
# Pixels: '#' full, '+' 2/3, '-' 1/3, '.' off.
#
#   python tools/gen_textfont.py                  writes the header
#   python tools/gen_textfont.py --preview x.png  also draws both fonts into x.png (needs Pillow)
import os
import sys

W, H = 4, 12
LEVEL = {'.': 0, '-': 1, '+': 2, '#': 3}
glyphs = {}          # code -> list of H rows, each W levels


def blank():
    return [[0] * W for _ in range(H)]


def put(code, rows, top=0):
    g = glyphs.get(code) or blank()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if LEVEL[ch]:
                g[top + y][x] = LEVEL[ch]
    glyphs[code] = g


def block(text):
    """A header line of characters at columns 1, 5, 9, ... then H art rows, 3 columns per glyph."""
    lines = [l for l in text.strip('\n').split('\n')]
    head, art = lines[0], lines[1:]
    assert len(art) == H, (head, len(art))
    for i in range(1, len(head), 4):
        ch = head[i]
        rows = [r[i - 1:i + 2] for r in art]
        assert all(len(r) == 3 for r in rows), (ch, rows)
        put(ord(ch), rows)


