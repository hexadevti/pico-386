# ---- accented letters: a base letter plus a mark, CP437 codes ------------------------------------
MARKS = {
    'acute': ['..#', '.#.'], 'grave': ['#..', '.#.'], 'circ': ['.#.', '#.#'],
    'diaer': ['#.#', '...'], 'tilde': ['#+.', '.+#'], 'ring': ['.#.', '#.#'],
}


def accented(code, base, mark, marks, top):
    """base with the mark's rows cleared first (so i loses its dot), then the mark."""
    g = [row[:] for row in glyphs[ord(base)]]
    for y in range(top, top + len(marks[mark])):
        g[y] = [0] * W
    glyphs[code] = g
    put(code, marks[mark], top)


