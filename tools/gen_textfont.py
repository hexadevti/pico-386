    f.write('// tools/gen_textfont.py: edit that, not this).\n//\n')
    f.write('// One byte per row, two bits per pixel (left pixel in the top bits): coverage 0..3.\n')
    f.write('// kFont4xNHas marks the codes drawn here; the rest are shrunk from the guest font.\n')
    f.write('#pragma once\n#include <stdint.h>\n')
    for h in (12, 8):
        gl = fonts[h]
        has = [0] * 8
        for c in gl:
            has[c >> 5] |= 1 << (c & 31)
        f.write('\nstatic const uint32_t kFont4x%dHas[8] = {\n  ' % h)
        f.write(', '.join('0x%08xu' % v for v in has))
        f.write('\n};\n\nstatic const uint8_t kFont4x%d[256][%d] = {\n' % (h, h))
        for c in range(256):
            g = gl.get(c) or [[0] * W for _ in range(h)]
            rows = [g[y][0] << 6 | g[y][1] << 4 | g[y][2] << 2 | g[y][3] for y in range(h)]
            f.write('  {' + ','.join('0x%02x' % v for v in rows) + '}, // %02X\n' % c)
        f.write('};\n')
        print('4x%d: %d glyphs' % (h, len(gl)))
