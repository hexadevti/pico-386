# gen_fmopl_compact.py -- writes pico386/src/pc/tiny386/fmopl_compact.h from upstream's tables
# (fmopl_table.h): the first 256 entries of TL_TABLE (6 dB; each further 256 steps halve, a
# shift) and a quarter of the sine as TL_TABLE indexes (the other quarters and the four OPL2 waves
# are folds of it, in fmopl.c's opl_out). 2 KB instead of the 128 KB the full tables take.
# Run: python -I tools/gen_fmopl_compact.py
import os, re
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'pico386', 'src', 'pc', 'tiny386')
t = open(os.path.join(here, 'fmopl_table.h'), encoding='utf-8').read()

def arr(name):
    m = re.search(r'%s\[\] = \{(.*?)\};' % name, t, re.S)
    return [x.strip() for x in m.group(1).split(',') if x.strip()]

tl = [int(x) for x in arr('TL_TABLE')]
sin = [int(x.replace('&TL_TABLE[', '').replace(']', '')) for x in arr('SIN_TABLE')]
quarter = [sin[s] for s in range(513)]
assert quarter[0] == 4095 and all(q < 4095 for q in quarter[1:])

def rows(v, n):
    return ',\n'.join(' ' + ', '.join(str(x) for x in v[i:i + n]) for i in range(0, len(v), n))

out = f"""/* fmopl_compact.h -- pico-386: generated by tools/gen_fmopl_compact.py from fmopl_table.h. Do not edit. */
/* TL_TABLE[0..255]: the output level for 0 to 6 dB of attenuation (0.0234375 dB steps) */
static const int32_t TL_EXP[256] = {{
{rows(tl[:256], 8)}
}};
/* SIN_TABLE[0..512] as TL_TABLE indexes: a quarter sine, 4095 (silence) at 0 */
static const uint16_t SIN_LOG[513] = {{
{rows(quarter, 16)}
}};
"""
open(os.path.join(here, 'fmopl_compact.h'), 'w', encoding='utf-8', newline='\n').write(out)
print('ok')
